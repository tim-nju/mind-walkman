import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { basename, join } from 'node:path';
import vm from 'node:vm';

const mode = process.argv[2];
assert.ok(['media', 'backup'].includes(mode), 'Usage: node scripts/hope-check.mjs media|backup');
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const source = JSON.parse(await readFile('docs/hope-source.json', 'utf8'));
const receipt = JSON.parse(await readFile('docs/qa/hope-media-receipt.json', 'utf8'));
const context = vm.createContext({});
vm.runInContext(await readFile('course-data.js', 'utf8') + ';globalThis.hope=HOPE_TOPIC;', context);
assert.equal(context.hope.tracks.length, 1);
assert.equal(receipt.status, 'pass');
assert.equal(receipt.checks.length, 1);
const track = context.hope.tracks[0];
const verified = receipt.checks[0];
assert.equal(verified.officialGuid, source.guid);
assert.equal(source.public, true);
assert.equal(source.show, 'The Hope');
assert.equal(source.youtubeOembedAuthor, source.show);
assert.equal(source.episode, 3);
assert.equal(source.mime, 'audio/mpeg');
assert.equal(track.id, 'hope-workplace-03');
assert.equal(track.mime, source.mime);
assert.equal(track.privateAudio, true);
assert.equal(track.fileName, basename(verified.path));
assert.equal(track.audioSrc, verified.path);
assert.equal(track.sha256, verified.sha256);
assert.equal(track.bytes, verified.bytes);
assert.equal(track.duration, verified.duration);
assert.equal(verified.decodeExitCode, 0);
assert.ok(Math.abs(track.duration - source.declaredDuration) < 1, 'Actual duration differs from official feed');
const local = await readFile(track.audioSrc);
assert.equal(digest(local), track.sha256, 'Official single-episode media SHA mismatch');
assert.equal(local.length, track.bytes);
if (mode === 'backup') {
  const backup = JSON.parse(await readFile('docs/qa/hope-backup-receipt.json', 'utf8'));
  assert.equal(backup.status, 'pass');
  assert.equal(backup.count, 1);
  assert.equal(backup.bytes, track.bytes);
  const manifestBytes = await readFile(join(backup.destination, 'manifest.json'));
  assert.equal(digest(manifestBytes), backup.manifestSha256);
  const manifest = JSON.parse(manifestBytes);
  assert.equal(manifest.files.length, 1);
  const saved = manifest.files[0];
  assert.equal(saved.id, track.id);
  assert.equal(saved.filename, track.fileName);
  assert.equal(saved.sha256, track.sha256);
  assert.equal(saved.bytes, track.bytes);
  const restored = await readFile(join(backup.destination, saved.filename));
  assert.equal(restored.length, track.bytes);
  assert.equal(digest(restored), track.sha256, 'Private backup readback SHA mismatch');
}
console.log(`PASS hope ${mode}: ${track.bytes} bytes ${track.sha256} duration=${track.duration}s; cloud sync unverified`);
